document.addEventListener('DOMContentLoaded', () => {
    const langButtons = document.querySelectorAll('.lang-btn');
    const i18nElements = document.querySelectorAll('[data-i18n]');

    // Check LocalStorage for saved language, default to English
    const savedLang = localStorage.getItem('phera_lang') || 'en';
    setLanguage(savedLang);

    // Update active button state on load
    langButtons.forEach(btn => {
        if (btn.getAttribute('data-lang') === savedLang) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });

    langButtons.forEach(btn => {
        btn.addEventListener('click', () => {
            // Update active state
            langButtons.forEach(b => b.classList.remove('active'));
            btn.classList.add('active');

            // Apply language
            const lang = btn.getAttribute('data-lang');
            setLanguage(lang);
        });
    });

    function setLanguage(lang) {
        if (!translations[lang]) return;

        // Save preference globally
        localStorage.setItem('phera_lang', lang);

        i18nElements.forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (translations[lang][key]) {
                if (el.tagName === 'INPUT' && el.type === 'text') {
                    // For inputs with placeholders we might need specialized handling
                } else if (el.tagName === 'TEXTAREA') {
                    // For textareas with placeholders
                } else {
                    el.innerHTML = translations[lang][key];
                }
            }
        });

        // Set HTML lang attribute
        document.documentElement.lang = lang;
    }
});
